"""Tests: report generation (Markdown/JSON artifacts, [HH:MM:SS] format).

Verifies the pure report-rendering helpers and the on-disk artifact set.
In the new architecture the AI content (summary, notes, quiz, flashcards, and
the full report) is generated by the active Hermes model in conversation;
this module still renders the template and the local artifacts.
"""

from __future__ import annotations

import json
import shutil
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from conftest import fake_metadata, fake_transcript, fake_visual  # noqa: E402

from scripts import report_generator
from scripts import main as main_mod  # noqa: E402


class _Analysis(dict):
    """Lightweight stand-in for a model's parsed AI result.

    Mirrors the original test fixture: the parsed JSON the model returns is
    wrapped under a ``parsed`` key (the raw text is also stored).
    """

    def __init__(self, parsed):
        super().__init__({"parsed": parsed,
                          "raw": json.dumps(parsed, ensure_ascii=False)})


SUMMARY = _Analysis({
    "executive_summary": "خلاصه اجرایی",
    "detailed_summary": "خلاصه مفصل",
    "main_points": ["نکته با [00:01:00]"],
    "key_facts": ["fact"],
    "conclusions": ["conclusion"],
})
TOPICS = _Analysis({"topics": [{"topic": "t", "start": "00:00:00",
                                 "end": "00:01:00", "description": "d"}],
                    "chapters": [{"title": "فصل ۱", "start": "00:00:00",
                                  "end": "00:01:00", "summary": "s"}]})
NOTES = _Analysis({"notes": [{"heading": "بخش", "content": "متن",
                              "key_concepts": ["c"], "definitions": [
                                  {"term": "term", "definition": "def"}],
                              "examples": ["ex"], "formulas": ["a=b"]}],
                   "glossary": [{"term": "g", "definition": "gd"}]})
QUIZ = _Analysis({"quiz": [
    {"type": "multiple_choice", "difficulty": "easy", "question": "q?",
     "options": ["a", "b", "c", "d"], "answer_index": 1,
     "explanation": "exp [00:00:05]"},
    {"type": "short_answer", "difficulty": "hard", "question": "q2?",
     "answer": "a2", "explanation": "e2"},
]})
FLASH = _Analysis({"flashcards": [{"front": "f", "back": "b",
                                    "category": "terminology"}]})


class TestSummaryRender(unittest.TestCase):
    def test_summary_sections(self):
        md = report_generator.render_summary_md(SUMMARY, fake_metadata())
        for section in ("خلاصه اجرایی", "خلاصه مفصل", "نکات اصلی",
                        "حقایق کلیدی", "نتیجه‌گیری‌ها"):
            self.assertIn(section, md)

    def test_missing_parsed_falls_back_gracefully(self):
        empty = {"parsed": None, "raw": "raw model text"}
        md = report_generator.render_summary_md(empty, fake_metadata())
        self.assertIn("در دسترس نیست", md)


class TestQuizAndFlashcardsRender(unittest.TestCase):
    def test_quiz_render(self):
        q_md, q_json = report_generator.render_quiz(QUIZ)
        self.assertIn("A) a", q_md)
        self.assertIn("B) b", q_md)
        self.assertIn("C) c", q_md)
        self.assertIn("D) d", q_md)
        self.assertIn("پاسخ صحیح", q_md)
        # quiz_json is already a dict, not a JSON string
        self.assertEqual(q_json["quiz"], QUIZ["parsed"]["quiz"])

    def test_flashcards_render(self):
        f_md, f_json = report_generator.render_flashcards(FLASH)
        self.assertIn("فلش‌کارت", f_md)
        self.assertEqual(f_json["flashcards"], FLASH["parsed"]["flashcards"])

    def test_quiz_json_structure(self):
        _, q_json = report_generator.render_quiz(QUIZ)
        self.assertEqual(len(q_json["quiz"]), 2)


class TestReportTemplate(unittest.TestCase):
    """The report template is written by the orchestrator; these tests
    verify the descriptor structure (no AI content) and provenance labels."""

    def test_template_content_has_no_ai_analysis(self):
        from scripts import config as cfg

        out = Path(cfg.data_dir()) / "output" / "TEMPLATE_TEST"
        out.mkdir(parents=True, exist_ok=True)
        try:
            # Render the template the same way main.py does.
            ws = report_generator.video_workspace(out, "TEMPLATE_TEST")
            report = main_mod.render_template(
                fake_metadata(), fake_transcript(), fake_visual())
            (ws / "report.md").write_text(report, encoding="utf-8")
            self.assertIn("شناسه:", report)
            self.assertIn("عنوان:", report)
            self.assertIn("متن پیاده‌سازی شده", report)
            # unspecified-source findings render under a labeled section too
            self.assertIn("یافته‌های تصویری", report)
            # AI content is added by the model in chat, not by the template.
            self.assertNotIn("خلاصه اجرایی", report)
        finally:
            shutil.rmtree(out, ignore_errors=True)

    def test_template_separates_ocr_from_transcript(self):
        """OCR findings must be labeled as OCR, never as transcription."""
        visual = [
            {"hhmmss": "[00:00:03]", "content_type": "slide", "source": "ocr",
             "visible_text": "Machine Learning", "description": "اسلاید"},
        ]
        report = main_mod.render_template(
            fake_metadata(), fake_transcript(), visual)
        self.assertIn("OCR", report)
        self.assertIn("نه گفتار، نه درک تصویری", report)
        # The transcript section is labeled as its own source.
        self.assertIn("متن پیاده‌سازی شده (منبع: transcript)", report)
        # OCR findings are not placed under the transcript section heading.
        self.assertNotIn("## متن پیاده‌سازی شده (منبع: OCR)", report)

    def test_template_labels_vision_observations(self):
        """Actual visual observations get their own labeled section."""
        visual = [
            {"hhmmss": "[00:00:03]", "content_type": "chart", "source": "vision",
             "description": "نمودار دایره‌ای", "visual_only_info": "رنگ قرمز"},
        ]
        report = main_mod.render_template(
            fake_metadata(), fake_transcript(), visual)
        self.assertIn("مشاهدات تصویری مدل", report)
        self.assertIn("تحلیل تصویری واقعی", report)

    def test_template_provenance_section(self):
        """The template always reports which evidence sources are present."""
        report = main_mod.render_template(
            fake_metadata(), fake_transcript(), fake_visual())
        self.assertIn("منابع شواهد", report)
        self.assertIn("پیاده‌سازی گفتار", report)
        self.assertIn("فراداده/توضیحات ویدیو", report)

    def test_template_without_transcript(self):
        """No transcript → no transcript section, provenance says missing."""
        report = main_mod.render_template(fake_metadata(), None, [])
        self.assertNotIn("## متن پیاده‌سازی شده", report)
        self.assertIn("در دسترس نیست", report)
